create table if not exists public.penerimaan_tunai_ketua_gang (
  id bigint generated by default as identity primary key,
  warga_id bigint not null references public.warga(id) on delete restrict,
  keluarga_id text,
  nama_warga text not null,
  gang text not null,
  alamat text,
  bulan date not null,
  total_amount integer not null default 35000 check (total_amount = 35000),
  status text not null default 'diterima'
    check (status in ('diterima','menunggu_setoran','disetorkan')),
  petugas_id bigint not null,
  petugas_nama text not null,
  qris_order_id text unique,
  iuran_id integer references public.iuran_warga(id) on delete set null,
  diterima_at timestamptz not null default now(),
  disetorkan_at timestamptz,
  created_at timestamptz not null default now()
);

create unique index if not exists uq_penerimaan_tunai_ketua_gang_keluarga_bulan
  on public.penerimaan_tunai_ketua_gang ((coalesce(keluarga_id, 'warga:' || warga_id::text)), bulan);

create index if not exists idx_penerimaan_tunai_ketua_gang_petugas
  on public.penerimaan_tunai_ketua_gang (petugas_id, created_at desc);
create index if not exists idx_penerimaan_tunai_ketua_gang_gang
  on public.penerimaan_tunai_ketua_gang (lower(gang), created_at desc);
create index if not exists idx_penerimaan_tunai_ketua_gang_status
  on public.penerimaan_tunai_ketua_gang (status, created_at desc);

alter table public.penerimaan_tunai_ketua_gang enable row level security;
revoke all on public.penerimaan_tunai_ketua_gang from anon, authenticated;
grant select, insert, update, delete on public.penerimaan_tunai_ketua_gang to service_role;
grant usage, select on sequence public.penerimaan_tunai_ketua_gang_id_seq to service_role;
