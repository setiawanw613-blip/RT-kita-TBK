-- Durable, idempotent retry attempts for GoBiz QRIS.
-- An attempt is committed before calling GoBiz so a timeout/database interruption
-- can safely resume with the same order_id and Idempotency-Key.
CREATE TABLE IF NOT EXISTS public.gobiz_payment_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  old_order_id text NOT NULL UNIQUE,
  order_id text NOT NULL UNIQUE,
  keluarga_id text NOT NULL,
  warga_id text NOT NULL,
  row_ids integer[] NOT NULL,
  total_amount integer NOT NULL CHECK (total_amount > 0),
  provider_transaction_id text,
  status text NOT NULL DEFAULT 'creating'
    CHECK (status IN ('creating', 'reserved', 'late_settlement_review')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.gobiz_payment_attempts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.gobiz_payment_attempts FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.gobiz_payment_attempts TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.gobiz_payment_attempts_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.start_gobiz_iuran_retry_attempt(
  p_old_order_id text,
  p_proposed_order_id text
)
RETURNS TABLE(order_id text, total_amount integer, attempt_status text)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_old public.iuran_midtrans_orders%ROWTYPE;
  v_attempt public.gobiz_payment_attempts%ROWTYPE;
  v_count integer;
  v_total integer;
BEGIN
  IF p_old_order_id IS NULL
     OR p_old_order_id !~ '^RTTBK-(PROD|SBX)-[0-9]+-[a-f0-9]{8}$'
     OR p_proposed_order_id IS NULL
     OR p_proposed_order_id !~ '^RTTBK-(PROD|SBX)-[0-9]+-[a-f0-9]{8}$'
     OR p_old_order_id = p_proposed_order_id THEN
    RAISE EXCEPTION 'REFERENSI_RETRY_GOBIZ_TIDAK_VALID' USING ERRCODE = '22023';
  END IF;

  SELECT a.* INTO v_attempt
  FROM public.gobiz_payment_attempts AS a
  WHERE a.old_order_id = p_old_order_id
  FOR UPDATE;

  IF FOUND THEN
    IF v_attempt.status NOT IN ('creating', 'reserved') THEN
      RAISE EXCEPTION 'ATTEMPT_RETRY_GOBIZ_PERLU_REVIEW' USING ERRCODE = '23514';
    END IF;
    RETURN QUERY SELECT v_attempt.order_id, v_attempt.total_amount, v_attempt.status;
    RETURN;
  END IF;

  SELECT o.* INTO v_old
  FROM public.iuran_midtrans_orders AS o
  WHERE o.order_id = p_old_order_id AND o.provider = 'gobiz'
  FOR UPDATE;

  IF NOT FOUND
     OR lower(coalesce(v_old.provider_status, '')) NOT IN
       ('expire', 'expired', 'cancel', 'cancelled', 'deny', 'denied') THEN
    RAISE EXCEPTION 'ORDER_LAMA_BELUM_TERBUKTI_KEDALUWARSA' USING ERRCODE = '23514';
  END IF;

  IF cardinality(coalesce(v_old.row_ids, ARRAY[]::integer[])) < 1 THEN
    RAISE EXCEPTION 'LEDGER_RETRY_GOBIZ_TIDAK_VALID' USING ERRCODE = '23514';
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('qris-iuran:' || v_old.keluarga_id::text, 0)
  );

  PERFORM 1 FROM public.iuran_warga
  WHERE id = ANY(v_old.row_ids)
  FOR UPDATE;

  SELECT count(*), coalesce(sum(total_amount), 0)::integer
    INTO v_count, v_total
  FROM public.iuran_warga
  WHERE id = ANY(v_old.row_ids)
    AND keluarga_id::text = v_old.keluarga_id::text
    AND bukti_transfer = 'GOBIZ:' || p_old_order_id
    AND status <> 'lunas'
    AND coalesce(total_amount, 0) = 35000;

  IF v_count <> cardinality(v_old.row_ids)
     OR v_total <> v_old.total_amount
     OR v_total <> v_count * 35000 THEN
    RAISE EXCEPTION 'IURAN_RETRY_GOBIZ_TIDAK_COCOK' USING ERRCODE = '23514';
  END IF;

  INSERT INTO public.gobiz_payment_attempts (
    old_order_id, order_id, keluarga_id, warga_id, row_ids, total_amount, status
  )
  VALUES (
    p_old_order_id, p_proposed_order_id, v_old.keluarga_id::text,
    v_old.warga_id::text, v_old.row_ids, v_old.total_amount, 'creating'
  );

  RETURN QUERY
  SELECT a.order_id, a.total_amount, a.status
  FROM public.gobiz_payment_attempts AS a
  WHERE a.old_order_id = p_old_order_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.complete_gobiz_iuran_retry_attempt(
  p_new_order_id text,
  p_new_transaction_id text
)
RETURNS SETOF public.iuran_warga
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_attempt public.gobiz_payment_attempts%ROWTYPE;
  v_old public.iuran_midtrans_orders%ROWTYPE;
  v_count integer;
  v_total integer;
BEGIN
  IF p_new_order_id IS NULL
     OR p_new_order_id !~ '^RTTBK-(PROD|SBX)-[0-9]+-[a-f0-9]{8}$'
     OR nullif(btrim(p_new_transaction_id), '') IS NULL THEN
    RAISE EXCEPTION 'REFERENSI_RETRY_GOBIZ_TIDAK_VALID' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_attempt
  FROM public.gobiz_payment_attempts
  WHERE order_id = p_new_order_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'ATTEMPT_RETRY_GOBIZ_TIDAK_DITEMUKAN' USING ERRCODE = 'P0002';
  END IF;

  IF v_attempt.status = 'reserved' THEN
    IF v_attempt.provider_transaction_id IS DISTINCT FROM p_new_transaction_id THEN
      RAISE EXCEPTION 'TRANSAKSI_RETRY_GOBIZ_TIDAK_COCOK' USING ERRCODE = '23514';
    END IF;
    RETURN QUERY
    SELECT * FROM public.iuran_warga
    WHERE id = ANY(v_attempt.row_ids)
    ORDER BY bulan ASC;
    RETURN;
  END IF;

  IF v_attempt.status <> 'creating' THEN
    RAISE EXCEPTION 'ATTEMPT_RETRY_GOBIZ_PERLU_REVIEW' USING ERRCODE = '23514';
  END IF;

  SELECT * INTO v_old
  FROM public.iuran_midtrans_orders
  WHERE order_id = v_attempt.old_order_id AND provider = 'gobiz'
  FOR UPDATE;

  IF NOT FOUND
     OR lower(coalesce(v_old.provider_status, '')) NOT IN
       ('expire', 'expired', 'cancel', 'cancelled', 'deny', 'denied') THEN
    RAISE EXCEPTION 'ORDER_LAMA_TIDAK_LAGI_KEDALUWARSA' USING ERRCODE = '23514';
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('qris-iuran:' || v_attempt.keluarga_id, 0)
  );

  PERFORM 1 FROM public.iuran_warga
  WHERE id = ANY(v_attempt.row_ids)
  FOR UPDATE;

  SELECT count(*), coalesce(sum(total_amount), 0)::integer
    INTO v_count, v_total
  FROM public.iuran_warga
  WHERE id = ANY(v_attempt.row_ids)
    AND keluarga_id::text = v_attempt.keluarga_id
    AND bukti_transfer = 'GOBIZ:' || v_attempt.old_order_id
    AND status <> 'lunas'
    AND coalesce(total_amount, 0) = 35000;

  IF v_count <> cardinality(v_attempt.row_ids)
     OR v_total <> v_attempt.total_amount
     OR v_total <> v_count * 35000 THEN
    RAISE EXCEPTION 'IURAN_RETRY_GOBIZ_TIDAK_COCOK' USING ERRCODE = '23514';
  END IF;

  UPDATE public.iuran_warga
  SET bukti_transfer = 'GOBIZ:' || p_new_order_id,
      gobiz_transaction_id = p_new_transaction_id,
      gobiz_status = 'pending',
      gobiz_settlement_at = NULL,
      gobiz_notification_at = NULL
  WHERE id = ANY(v_attempt.row_ids);

  INSERT INTO public.iuran_midtrans_orders (
    order_id, keluarga_id, warga_id, row_ids, total_amount,
    provider, provider_transaction_id, provider_status,
    jalur_pembayaran, disetorkan_oleh_id, disetorkan_oleh_nama
  )
  VALUES (
    p_new_order_id, v_old.keluarga_id, v_old.warga_id, v_attempt.row_ids,
    v_attempt.total_amount, 'gobiz', p_new_transaction_id, 'pending',
    v_old.jalur_pembayaran, v_old.disetorkan_oleh_id, v_old.disetorkan_oleh_nama
  );

  UPDATE public.gobiz_payment_attempts
  SET provider_transaction_id = p_new_transaction_id,
      status = 'reserved',
      updated_at = now()
  WHERE order_id = p_new_order_id;

  RETURN QUERY
  SELECT * FROM public.iuran_warga
  WHERE id = ANY(v_attempt.row_ids)
  ORDER BY bulan ASC;
END;
$$;

REVOKE ALL ON FUNCTION public.start_gobiz_iuran_retry_attempt(text,text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.complete_gobiz_iuran_retry_attempt(text,text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.start_gobiz_iuran_retry_attempt(text,text) TO service_role;
GRANT EXECUTE ON FUNCTION public.complete_gobiz_iuran_retry_attempt(text,text) TO service_role;

COMMENT ON TABLE public.gobiz_payment_attempts
IS 'Durable server-only GoBiz retry attempts. Stable order_id lets the app resume the same idempotent provider request after network or database interruptions.';
