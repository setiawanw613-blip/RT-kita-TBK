CREATE TABLE IF NOT EXISTS public.iuran_warga_manual (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_warga text NOT NULL CHECK (length(trim(nama_warga)) BETWEEN 2 AND 120),
  gang text,
  alamat text,
  bulan date NOT NULL,
  total_amount integer NOT NULL DEFAULT 35000 CHECK (total_amount = 35000),
  jalur_pembayaran text NOT NULL DEFAULT 'tunai_door_to_door_manual' CHECK (jalur_pembayaran = 'tunai_door_to_door_manual'),
  status text NOT NULL DEFAULT 'diterima_manual' CHECK (status IN ('diterima_manual','terhubung_ke_data_warga')),
  linked_warga_id bigint REFERENCES public.warga(id) ON DELETE SET NULL,
  petugas_id text,
  petugas_nama text NOT NULL,
  kas_rt_id bigint,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.iuran_warga_manual ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.iuran_warga_manual FROM anon, authenticated;
GRANT ALL ON TABLE public.iuran_warga_manual TO service_role;

CREATE UNIQUE INDEX IF NOT EXISTS iuran_warga_manual_identitas_bulan_uidx
ON public.iuran_warga_manual (
  lower(trim(nama_warga)),
  COALESCE(lower(trim(gang)), ''),
  COALESCE(lower(trim(alamat)), ''),
  bulan
);

CREATE OR REPLACE FUNCTION public.catat_iuran_manual_atomic(
  p_nama_warga text,
  p_gang text,
  p_alamat text,
  p_bulan date,
  p_petugas_id text,
  p_petugas_nama text
) RETURNS public.iuran_warga_manual
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_manual public.iuran_warga_manual;
  v_kas_id bigint;
BEGIN
  IF p_nama_warga IS NULL OR length(trim(p_nama_warga)) < 2 OR length(trim(p_nama_warga)) > 120 THEN
    RAISE EXCEPTION 'Nama warga tidak valid' USING ERRCODE = '22023';
  END IF;
  IF p_bulan IS NULL OR extract(day from p_bulan) <> 1 THEN
    RAISE EXCEPTION 'Bulan iuran tidak valid' USING ERRCODE = '22023';
  END IF;
  IF p_petugas_nama IS NULL OR length(trim(p_petugas_nama)) = 0 THEN
    RAISE EXCEPTION 'Nama petugas wajib diisi' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.iuran_warga_manual
    (nama_warga, gang, alamat, bulan, total_amount, petugas_id, petugas_nama)
  VALUES
    (trim(p_nama_warga), NULLIF(trim(p_gang), ''), NULLIF(trim(p_alamat), ''),
     p_bulan, 35000, NULLIF(trim(p_petugas_id), ''), trim(p_petugas_nama))
  RETURNING * INTO v_manual;

  INSERT INTO public.kas_rt (tanggal, jenis, keterangan, jumlah, kategori)
  VALUES (
    current_date,
    'pemasukan',
    'Iuran tunai warga non-aplikasi: ' || trim(p_nama_warga) ||
      ' · ' || to_char(p_bulan, 'YYYY-MM'),
    35000,
    'Iuran Warga'
  )
  RETURNING id INTO v_kas_id;

  UPDATE public.iuran_warga_manual
  SET kas_rt_id = v_kas_id
  WHERE id = v_manual.id
  RETURNING * INTO v_manual;

  RETURN v_manual;
END;
$$;

REVOKE ALL ON FUNCTION public.catat_iuran_manual_atomic(text,text,text,date,text,text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.catat_iuran_manual_atomic(text,text,text,date,text,text) TO service_role;
