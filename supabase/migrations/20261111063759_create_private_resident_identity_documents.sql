create table if not exists public.dokumen_identitas (
  id bigint generated by default as identity primary key,
  keluarga_id bigint not null references public.keluarga(id) on delete cascade,
  warga_id bigint null references public.warga(id) on delete set null,
  jenis_dokumen text not null check (jenis_dokumen in ('KK','KTP')),
  storage_path text not null unique,
  nama_file text not null,
  mime_type text not null check (mime_type in ('image/jpeg','image/png','image/webp','application/pdf')),
  ukuran_bytes bigint not null check (ukuran_bytes > 0 and ukuran_bytes <= 8388608),
  ocr_text text,
  ocr_data jsonb not null default '{}'::jsonb,
  status_verifikasi text not null default 'menunggu_verifikasi'
    check (status_verifikasi in ('menunggu_verifikasi','terverifikasi','perlu_perbaikan')),
  uploaded_by text,
  uploaded_at timestamptz not null default now()
);

create index if not exists dokumen_identitas_keluarga_idx
  on public.dokumen_identitas (keluarga_id, jenis_dokumen, uploaded_at desc);

alter table public.dokumen_identitas enable row level security;
revoke all on public.dokumen_identitas from public, anon, authenticated;
grant all on public.dokumen_identitas to service_role;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'dokumen-identitas',
  'dokumen-identitas',
  false,
  8388608,
  array['image/jpeg','image/png','image/webp','application/pdf']
)
on conflict (id) do update set
  public = false,
  file_size_limit = 8388608,
  allowed_mime_types = excluded.allowed_mime_types;
